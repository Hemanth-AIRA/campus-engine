def detect_rejected_skills(transcript, mandatory_skills, room_id="", process_id=0):
    """
    Async-safe function: detects if candidate EXPLICITLY said they don't know specific skills.
    Very conservative — only returns skills on clear, unambiguous rejection.
    Designed to run in a background thread during ack speech.
    
    Returns: list of rejected skill strings (subset of mandatory_skills), or empty list.
    """
    import logging
    import json
    from openai import OpenAI
    logger = logging.getLogger(__name__)
    log_prefix = f"[process id: {process_id}][room id: {room_id}]"
    
    if not transcript or not mandatory_skills:
        return []
    
    # Quick keyword pre-filter — only call GPT if transcript contains rejection language
    rejection_keywords = [
        "don't know", "dont know", "do not know",
        "no experience", "no idea", "not familiar",
        "haven't worked", "havent worked", "have not worked",
        "never used", "never worked", "not worked",
        "don't have experience", "dont have experience",
        "can't", "cannot", "not sure about",
        "haven't used", "havent used", "have not used",
        "don't understand", "dont understand",
        "not aware", "no knowledge", "zero experience",
        "i skip", "skip this"
    ]
    
    transcript_lower = transcript.lower()
    has_rejection = any(kw in transcript_lower for kw in rejection_keywords)
    if not has_rejection:
        return []
    
    skills_list = "\n".join(f"- {s.strip()}" for s in mandatory_skills)
    
    prompt = f"""You are an interview skill rejection detector. Your job is to identify if the candidate EXPLICITLY stated they do NOT know specific mandatory skills.

MANDATORY SKILLS LIST:
{skills_list}

CANDIDATE TRANSCRIPT:
"{transcript}"

RULES (be VERY conservative — false positives are worse than false negatives):
1. ONLY return skills the candidate EXPLICITLY said they don't know/haven't used
2. The candidate must clearly name or reference the specific skill/technology
3. "I don't know" alone (without naming a skill) → return EMPTY list
4. "I'm not sure about the answer" → return EMPTY list (they're unsure about the question, not rejecting a skill)
5. "I haven't worked much with X" → INCLUDE (clear rejection)
6. "I'm still learning X" → DO NOT include (they know it partially)
7. "I don't know Java" when asked about Spring Boot → return ["Java programming language"] (match to the closest mandatory skill)
8. Only return skills that appear in the MANDATORY SKILLS LIST above (match by technology name)
9. If the candidate says they don't know the parent technology (e.g., "Java"), also include child/dependent skills (e.g., "Spring", "Hibernate") from the list
10. MULTI-SKILL QUESTION: If asked about multiple skills (e.g., "HTML and CSS") and candidate just says "I don't know" (without naming them), return EMPTY list. Do not assume they lack both.

Return ONLY a JSON array of rejected skill strings, exactly as they appear in the mandatory skills list.
Return [] if no explicit skill rejection is detected.
Do NOT explain, just return the JSON array."""

    try:
        client_oai = OpenAI()
        start = time.time()
        response = client_oai.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": prompt}],
            temperature=0,
            max_tokens=200
        )
        raw = response.choices[0].message.content.strip()
        elapsed = time.time() - start
        
        # Parse JSON array
        rejected = json.loads(raw)
        if not isinstance(rejected, list):
            rejected = []
        
        # Validate — only keep skills that actually exist in mandatory_skills
        valid_rejected = [s for s in rejected if s.strip() in [m.strip() for m in mandatory_skills]]
        
        if valid_rejected:
            logger.info(
                f"🚫 {log_prefix} SKILL REJECTION DETECTED | {elapsed*1000:.0f}ms | "
                f"rejected={valid_rejected}"
            )
        else:
            logger.debug(
                f"🔍 {log_prefix} Skill rejection check: none detected | {elapsed*1000:.0f}ms"
            )
        
        return valid_rejected
        
    except Exception as e:
        logger.warning(f"⚠️ {log_prefix} Skill rejection detection failed: {e}")
        return []


