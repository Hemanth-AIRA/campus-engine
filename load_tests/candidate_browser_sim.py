"""
candidate_browser_sim.py

Browser-based candidate simulator.

Instead of the Python LiveKit SDK, this opens a REAL Chromium browser window
at the candidate_join_url.  The browser handles everything natively:
  - Socket.IO join  → bot sees candidate, recruiter sees tile
  - WebRTC peer connection → recruiter video grid tile appears automatically
  - LiveKit track publish  → bot Python SDK receives audio (livekit=1 in URL)

Fake microphone:
  Chrome flag  --use-fake-device-for-media-stream  enables a software mic.
  Chrome flag  --use-file-for-fake-audio-capture=<wav>  feeds a WAV as mic input.
  This gives the bot real audio to transcribe without needing a hardware mic.

Usage (standalone):
    python -m load_tests.candidate_browser_sim \
        --url "https://devconnect.airacampus.com/?t=...&livekit=1" \
        --duration 120 \
        --audio load_tests/audio/candidate_speech.wav

Usage (from test_06):
    result = await run_browser_candidate(
        candidate_join_url=row["candidate_join_url"],
        candidate_name=row["candidate_name"],
        room_id=row["room_id"],
        duration_sec=130,
        audio_file="load_tests/audio/candidate_speech.wav",
    )
"""

import asyncio
import logging
import os
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from playwright.async_api import async_playwright, Browser, BrowserContext, Page

logger = logging.getLogger("candidate_browser_sim")

# Default fake-audio WAV (generated by gen_candidate_audio.py)
DEFAULT_AUDIO = str(Path(__file__).parent / "audio" / "candidate_speech.wav")

# ─────────────────────────────────────────────────────────────────────────────
# Result dataclass
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class BrowserCandidateResult:
    room_id: str
    candidate_name: str
    joined: bool = False
    livekit_connected: bool = False
    duration_sec: float = 0.0
    error: Optional[str] = None
    console_errors: list = field(default_factory=list)
    events: list = field(default_factory=list)

    def event(self, msg: str):
        ts = time.strftime("%H:%M:%S")
        self.events.append(f"[{ts}] {msg}")
        logger.info("[browser-sim][%s] %s", self.room_id, msg)


# ─────────────────────────────────────────────────────────────────────────────
# Core runner
# ─────────────────────────────────────────────────────────────────────────────

async def run_browser_candidate(
    candidate_join_url: str,
    candidate_name: str,
    room_id: str,
    duration_sec: float = 130.0,
    audio_file: str = DEFAULT_AUDIO,
    headless: bool = True,
    slow_mo: int = 0,
) -> BrowserCandidateResult:
    """
    Open a Chromium browser at candidate_join_url, grant mic/camera,
    let it run for duration_sec, then close.

    Returns BrowserCandidateResult with join status and any errors.
    """
    result = BrowserCandidateResult(room_id=room_id, candidate_name=candidate_name)
    audio_path = Path(audio_file).resolve()

    if not audio_path.exists():
        result.error = f"Audio file not found: {audio_path}"
        result.event(f"❌ {result.error}")
        return result

    result.event(f"🌐 Launching browser for {candidate_name} in room {room_id}")
    t0 = time.time()

    async with async_playwright() as pw:
        # Chrome args that enable fake microphone from WAV file
        browser: Browser = await pw.chromium.launch(
            headless=headless,
            slow_mo=slow_mo,
            args=[
                "--use-fake-device-for-media-stream",
                f"--use-file-for-fake-audio-capture={audio_path}",
                "--use-fake-ui-for-media-stream",   # auto-accept mic/cam permission
                "--disable-web-security",
                "--no-sandbox",
                "--disable-setuid-sandbox",
                "--disable-dev-shm-usage",
                "--autoplay-policy=no-user-gesture-required",
                "--disable-features=IsolateOrigins,site-per-process",
            ],
        )

        ctx: BrowserContext = await browser.new_context(
            permissions=["microphone", "camera"],
            ignore_https_errors=True,
        )

        page: Page = await ctx.new_page()

        # Capture console errors for debugging
        page.on("console", lambda msg: (
            result.console_errors.append(f"[{msg.type}] {msg.text}")
            if msg.type in ("error", "warning")
            else None
        ))
        page.on("pageerror", lambda err: result.console_errors.append(f"[pageerror] {err}"))

        try:
            result.event(f"📡 Navigating to candidate URL...")
            await page.goto(candidate_join_url, wait_until="domcontentloaded", timeout=30_000)
            result.event("✅ Page loaded")

            # Wait for Socket.IO join confirmation
            # The Connect UI shows a "Joined" state or the interview controls appear
            joined = await _wait_for_join(page, result)
            result.joined = joined

            if joined:
                result.event(f"✅ Candidate joined room successfully")

                # Check if LiveKit connected (livekit=1 in URL)
                lk_connected = await _check_livekit_connected(page)
                result.livekit_connected = lk_connected
                result.event(f"{'✅' if lk_connected else '⚠️'} LiveKit connected: {lk_connected}")

                # Stay in the interview for the full duration
                result.event(f"⏳ Staying in interview for {duration_sec:.0f}s...")
                await asyncio.sleep(duration_sec)
                result.event("✅ Duration elapsed — leaving interview")
            else:
                result.error = "Timed out waiting for candidate to join"
                result.event(f"❌ {result.error}")

        except Exception as e:
            result.error = str(e)
            result.event(f"❌ Browser error: {e}")
            logger.exception("[browser-sim][%s] Browser exception", room_id)

        finally:
            result.duration_sec = time.time() - t0
            await ctx.close()
            await browser.close()
            result.event(f"🔚 Browser closed after {result.duration_sec:.1f}s")

    return result


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

async def _wait_for_join(page: Page, result: BrowserCandidateResult, timeout: float = 30.0) -> bool:
    """
    Wait until the candidate is confirmed to be in the room.
    Looks for DOM signals that the Connect UI has joined:
      - The video-grid element is visible
      - OR the local-video element is present
      - OR window.__joined is set by App.jsx
    """
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            # Check if App.jsx has set a join flag
            joined_flag = await page.evaluate("() => window.__joined || false")
            if joined_flag:
                return True

            # Check if video-grid is in DOM (means interview UI rendered)
            grid = await page.query_selector("#video-grid")
            if grid:
                return True

            # Check if local video is present
            local_vid = await page.query_selector("#local-video, video")
            if local_vid:
                return True

        except Exception:
            pass

        await asyncio.sleep(1.0)
        elapsed = time.time() - (deadline - timeout)
        if int(elapsed) % 5 == 0:
            result.event(f"⏳ Waiting for join... {elapsed:.0f}s")

    return False


async def _check_livekit_connected(page: Page) -> bool:
    """Check if the LiveKit room is connected via window.__liveKitRoom."""
    try:
        connected = await page.evaluate("""
            () => {
                const room = window.__liveKitRoom;
                if (!room) return false;
                // LiveKit Room.state: 'connected' = 1
                return room.state === 'connected' || room.state === 1;
            }
        """)
        return bool(connected)
    except Exception:
        return False


# ─────────────────────────────────────────────────────────────────────────────
# CLI entry point — for quick manual testing
# ─────────────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Browser-based candidate simulator")
    parser.add_argument("--url", required=True, help="candidate_join_url from DB")
    parser.add_argument("--name", default="Test Candidate", help="Candidate name")
    parser.add_argument("--room", default="TEST-ROOM", help="Room ID")
    parser.add_argument("--duration", type=float, default=120.0, help="Seconds to stay in interview")
    parser.add_argument("--audio", default=DEFAULT_AUDIO, help="WAV file to use as fake mic")
    parser.add_argument("--headless", action="store_true", default=True, help="Run headless (default)")
    parser.add_argument("--visible", action="store_true", help="Show browser window")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")

    async def main():
        result = await run_browser_candidate(
            candidate_join_url=args.url,
            candidate_name=args.name,
            room_id=args.room,
            duration_sec=args.duration,
            audio_file=args.audio,
            headless=not args.visible,
        )
        print("\n=== RESULT ===")
        print(f"  Joined:          {result.joined}")
        print(f"  LiveKit:         {result.livekit_connected}")
        print(f"  Duration:        {result.duration_sec:.1f}s")
        print(f"  Error:           {result.error}")
        print(f"  Events ({len(result.events)}):")
        for e in result.events:
            print(f"    {e}")
        if result.console_errors:
            print(f"  Console errors ({len(result.console_errors)}):")
            for e in result.console_errors[:10]:
                print(f"    {e}")

    asyncio.run(main())
